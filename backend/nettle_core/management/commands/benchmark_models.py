"""Bonus (after the timebox): compare models on the same real assessments.

    python manage.py benchmark_models [--runs 2] [--models ...] [--out results.json]

Every run is a real report, titled "Benchmark: <model> #<n>", generated by the normal
worker. It is internal tooling, so it skips the organization's allowed-model list.
Runs on one assessment go one after another (one active generation per assessment
and template); the two assessments run side by side, so start two workers. Udine
reports are also scored against the five risk improvement recommendations in the
survey PDF, by an Opus judge.
"""
import json
import statistics
import time

from django.core.management.base import BaseCommand

from ai.client import AnthropicClient, LLMError
from ai.models import AIUsage
from ai.pricing import MODEL_LABELS, cost_usd
from assessments.models import Assessment
from reports.models import Report, ReportTemplate
from reports.tasks import generate_report_task
from tenancy.db import tenant_transaction
from tenancy.models import Organization

MODELS = ["claude-opus-5-5", "claude-sonnet-5-5", "claude-haiku-5-5"]
JUDGE_MODEL = "claude-opus-5-5"
CASES = [
    # organization, assessment title, template key
    ("default-insurer", "Q4 Warehouse Risk Review - Pacific Coast", "property-cope-survey"),
    ("customer-a", "Hazardous goods warehouse survey - Udine", "property-cope-survey"),
]
SCORED_CASE = "customer-a"
# The Udine survey's own risk improvement advice (sample_evidence PDF, pages 3-4). It is
# part of the evidence, so the score measures whether a report carries every
# recommendation the evidence supports: completeness, not independent judgement.
EXPERT_RECOMMENDATIONS = [
    "High rack storage under a 14.7 m ceiling: no ceiling-only sprinkler design protects flammable "
    "liquids and aerosols at this height; adapt the sprinkler concept to the stored goods.",
    "Solid piled inbound/outbound buffer storage under the 9.1 m ceiling: with ignitable liquids, "
    "limit stacks to 1.5 m (FM 7-29) or adapt the storage and sprinkler concept.",
    "Flow-through (multi-row) racks: limit ignitable-liquid container sizes (60 ml; 4 l if "
    "water-miscible) and protect with a horizontal solid barrier, Scheme A per FM 7-29.",
    "Aerosol storage: segregate aerosols above NFPA 30B Level 1 with a solid vertical barrier in the "
    "flue space and a solid barrier above every second rack level; dedicated rooms with adequate "
    "sprinklers for Level 2-3.",
    "Earthquake protection: brace the sprinkler piping, design the sprinkler tanks for earthquakes, "
    "and bolt the racks to the ground.",
]
JUDGE_SYSTEM = (
    "You compare the recommendations of an AI-drafted property risk survey with those of the "
    "expert engineer who surveyed the site. Judge substance, not wording or language: the "
    "survey may be written in Italian. An expert item is 'covered' when a recommendation asks "
    "for essentially the same action for the same hazard and area, 'partial' when it addresses "
    "the hazard but misses or weakens the key action, and 'missed' otherwise. Then list the "
    "survey recommendations that match no expert item."
)
JUDGE_SCHEMA = {
    "type": "object",
    "properties": {
        "items": {
            "type": "array",
            "items": {
                "type": "object",
                "properties": {
                    "expert_item": {"type": "integer"},
                    "verdict": {"type": "string", "enum": ["covered", "partial", "missed"]},
                    "matched_recommendations": {"type": "array", "items": {"type": "integer"}},
                    "reason": {"type": "string"},
                },
                "required": ["expert_item", "verdict", "matched_recommendations", "reason"],
                "additionalProperties": False,
            },
        },
        "unmatched_recommendations": {"type": "array", "items": {"type": "integer"}},
    },
    "required": ["items", "unmatched_recommendations"],
    "additionalProperties": False,
}
TIMEOUT_SECONDS = 900


class Command(BaseCommand):
    help = "Bonus: generate the same reports with several models and compare them."

    def add_arguments(self, parser):
        parser.add_argument("--runs", type=int, default=2)
        parser.add_argument("--models", nargs="+", default=MODELS)
        parser.add_argument("--out", default="benchmark-results.json")

    def handle(self, *args, runs, models, out, **options):
        lanes = []
        for slug, title, template_key in CASES:
            organization = Organization.objects.get(slug=slug)
            with tenant_transaction(organization):
                assessment = Assessment.objects.select_related("client").get(title=title)
                template = ReportTemplate.objects.get(key=template_key, is_active=True)
            # Each model's first run, then the second runs: as far apart as possible,
            # though a second run can still read the first one's prompt cache.
            pending = [(model, n) for n in range(1, runs + 1) for model in models]
            lanes.append({"org": organization, "assessment": assessment, "template": template, "pending": pending})

        results = []
        while any(lane["pending"] or lane.get("report") for lane in lanes):
            for lane in lanes:
                if lane.get("report") is None and lane["pending"]:
                    lane["report"], lane["started"] = self._start(lane, *lane["pending"].pop(0)), time.monotonic()
                elif lane.get("report") is not None:
                    with tenant_transaction(lane["org"]):
                        report = Report.objects.get(pk=lane["report"].pk)
                    timed_out = time.monotonic() - lane["started"] > TIMEOUT_SECONDS
                    if report.status in ("completed", "failed") or timed_out:
                        results.append(self._measure(lane["org"], report))
                        self.stdout.write(json.dumps(results[-1]["summary"]))
                        lane["report"] = None
            time.sleep(5)

        summary = _summarise(results)
        with open(out, "w") as handle:
            json.dump({"runs": results, "summary": summary}, handle, indent=2, default=str)
        self.stdout.write(_markdown(summary))

    def _start(self, lane, model, n):
        organization, assessment, template = lane["org"], lane["assessment"], lane["template"]
        with tenant_transaction(organization):
            report = Report.objects.create(
                organization=organization,
                assessment=assessment,
                template=template,
                title=f"Benchmark: {MODEL_LABELS.get(model, model)} #{n} - {assessment.client.name}",
                status="queued",
                language=template.language,
                ai_model=model,
                progress_total=len(template.ordered_sections()),
            )
            generate_report_task.enqueue(organization_id=str(organization.id), report_id=str(report.id))
        return report

    def _measure(self, organization, report):
        with tenant_transaction(organization):
            answers = list(report.answers.all())
            failed_calls = AIUsage.objects.filter(report=report, purpose__endswith=":failed").count()
        citations, recommendations = [], []
        for answer in answers:
            citations += answer.citations
            if isinstance(answer.value, list):  # a recommendations question
                recommendations += answer.value
                citations += [c for item in answer.value for c in item.get("citations", [])]
        quotes = [c for c in citations if c.get("quote")]
        duration = (report.finished_at - report.started_at).total_seconds() if report.finished_at else None
        run = {
            "case": organization.slug,
            "model": report.ai_model,
            "report_id": str(report.id),
            "status": report.status,
            "error": report.error_message,
            "seconds": round(duration) if duration else None,
            "cost_usd": float(report.cost_usd or 0),
            "tokens": {
                "input": report.input_tokens,
                "output": report.output_tokens,
                "cache_read": report.cache_read_tokens,
                "cache_write": report.cache_write_tokens,
            },
            "answers": len(answers),
            "answered": sum(a.status == "answered" for a in answers),
            "insufficient_evidence": sum(a.status == "insufficient_evidence" for a in answers),
            "quotes": len(quotes),
            "quotes_verified": sum(bool(c.get("verified")) for c in quotes),
            "recommendations": len(recommendations),
            "failed_calls": failed_calls,
        }
        if organization.slug == SCORED_CASE and report.status == "completed":
            run["judge"] = self._judge(organization, report, recommendations)
        run["summary"] = {k: run.get(k) for k in ("case", "model", "status", "seconds", "cost_usd", "answered", "recommendations")}
        run["summary"]["recall"] = run.get("judge", {}).get("recall")
        return run

    def _judge(self, organization, report, recommendations):
        expert = "\n".join(f"{i}. {text}" for i, text in enumerate(EXPERT_RECOMMENDATIONS, 1))
        drafted = "\n".join(
            f"{i}. [{item.get('priority')}] {item.get('title')}\n   Observation: {item.get('observation')}\n"
            f"   Action: {item.get('action')}"
            for i, item in enumerate(recommendations, 1)
        )
        text = f"<expert_recommendations>\n{expert}\n</expert_recommendations>\n<survey_recommendations>\n{drafted or '(none)'}\n</survey_recommendations>"
        try:
            result = AnthropicClient().generate_json(
                model=JUDGE_MODEL, system=JUDGE_SYSTEM, content=[{"type": "text", "text": text}], schema=JUDGE_SCHEMA, max_tokens=8000
            )
        except LLMError as exc:
            return {"error": str(exc), "recall": None}
        with tenant_transaction(organization):
            AIUsage.objects.create(
                organization=organization, report=report, purpose="benchmark:judge", model=result.model,
                cost_usd=cost_usd(result.model, **result.usage), **result.usage,
            )
        verdicts = {item["expert_item"]: item["verdict"] for item in result.data["items"]}
        score = sum({"covered": 1, "partial": 0.5}.get(verdicts.get(i), 0) for i in range(1, len(EXPERT_RECOMMENDATIONS) + 1))
        return {
            "recall": round(score / len(EXPERT_RECOMMENDATIONS), 2),
            "verdicts": result.data["items"],
            "unmatched_recommendations": result.data["unmatched_recommendations"],
            "judge_cost_usd": float(cost_usd(result.model, **result.usage) or 0),
        }


def _summarise(results):
    summary = []
    for case, _, _ in CASES:
        for model in MODELS:
            runs = [r for r in results if r["case"] == case and r["model"] == model]
            done = [r for r in runs if r["status"] == "completed"]
            if not runs:
                continue
            mean = lambda key, digits=1: round(statistics.mean(r[key] for r in done), digits) if done else None  # noqa: E731
            recalls = [r["judge"]["recall"] for r in done if r.get("judge", {}).get("recall") is not None]
            summary.append({
                "case": case,
                "model": model,
                "runs": len(runs),
                "completed": len(done),
                "seconds": mean("seconds"),
                "cost_usd": mean("cost_usd", 4),
                "answered": mean("answered"),
                "insufficient_evidence": mean("insufficient_evidence"),
                "quotes_verified": f"{sum(r['quotes_verified'] for r in done)}/{sum(r['quotes'] for r in done)}",
                "recommendations": mean("recommendations"),
                "recall": recalls or None,
                "failed_calls": sum(r["failed_calls"] for r in runs),
            })
    return summary


def _recall(values):
    return f"{statistics.mean(values):.2f} ({', '.join(f'{v:.1f}' for v in values)})" if values else "-"


def _markdown(summary):
    lines = [
        "| Case | Model | Completed | Time (s) | Cost ($) | Answered | Insufficient | Quotes verified | Recommendations | Recall | Failed calls |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for row in summary:
        lines.append(
            f"| {row['case']} | {MODEL_LABELS.get(row['model'], row['model'])} | {row['completed']}/{row['runs']} | "
            f"{row['seconds']} | {row['cost_usd']} | {row['answered']} | {row['insufficient_evidence']} | "
            f"{row['quotes_verified']} | {row['recommendations']} | {_recall(row['recall'])} | {row['failed_calls']} |"
        )
    return "\n".join(lines)
